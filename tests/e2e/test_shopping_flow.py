"""End-to-end scenario, one test per case of the data file (data/shopping_cases.json, or --cases / SHOP_CASES).

The `shopping_case` parameter is generated by pytest_generate_tests in tests/plugins/cases.py."""

from pathlib import Path

import allure
from playwright.sync_api import Page
import pytest

from shop.artifacts import RunArtifacts
from shop.config import Credentials
from shop.models import AddStatus, ShoppingCase
from shop.workflow import ShoppingWorkflow


@allure.story("Search under a price, add to cart, check the cart total")
@pytest.mark.e2e
def test_shopping_flow(
    shopping_case: ShoppingCase,
    page: Page,
    base_url: str,
    output_path: str,
    shop_credentials: Credentials | None,
) -> None:
    allure.dynamic.title(shopping_case.name)
    artifacts = RunArtifacts(Path(output_path))
    workflow = ShoppingWorkflow(page, base_url, artifacts, credentials=shop_credentials)
    try:
        result = workflow.run(shopping_case)
    finally:
        artifacts.save_log()

    found = result.search.products
    # The returned URLs are the collected products, within the limit, without duplicates.
    assert [product.url for product in found] == result.urls
    assert len(result.urls) <= shopping_case.limit
    assert len(set(result.urls)) == len(result.urls), "search returned duplicate URLs"
    assert all(product.price <= shopping_case.max_price for product in found)
    # Cross-check on another page: every added item's price on its own product page is within max_price.
    added = result.with_status(AddStatus.ADDED)
    assert all(item.page_price is not None and item.page_price <= shopping_case.max_price for item in added), [
        (item.title, item.page_price) for item in added
    ]
    # Expected outcomes from the data file.
    if shopping_case.expect_empty:
        assert result.urls == []
    assert len(result.urls) >= shopping_case.min_results
    if shopping_case.limit:
        assert len(result.search.pages) >= shopping_case.min_search_pages, f"result pages read: {result.search.pages}"
    # Adding: the shop must accept every product we could fill in. A refusal ('Please select ...', 'Enter valid
    # recipient name') means we missed an option or a required field. Only products the shop itself marks as not
    # buyable (unavailable) and forms we cannot fill (a required file upload: unsupported) are skipped.
    rejected = result.with_status(AddStatus.REJECTED)
    assert not rejected, [(item.title, item.message) for item in rejected]
    # An empty cart always passes the budget check, so found products must lead to at least one added item.
    if result.urls:
        assert added, [(item.title, item.status.value, item.message) for item in result.items]
    # The budget check counted one unit per URL (as in the assignment) or the chosen quantities (max_quantity);
    # the cart must hold exactly the units that were added.
    assert all(1 <= item.quantity <= shopping_case.max_quantity for item in result.items)
    assert result.cart.quantity == sum(item.quantity for item in added)
    # The random variants were really applied: each added product's cart line lists the values that were chosen
    # (the shop would otherwise accept its defaults silently, and the run log would claim choices never made).
    # Values, not captions: the cart names an attribute by its name, the product page may show another prompt
    # (the live Phone Cover asks 'Manufacturer', its cart line says 'Custom Text').
    cart_lines = {entry.title: list(entry.attributes.values()) for entry in result.cart.entries}
    for item in added:
        missing = [value for value in item.options.values() if value not in cart_lines.get(item.title, [])]
        assert not missing, (item.title, item.options, cart_lines.get(item.title))
    # The budget was checked against the Sub-Total; it must be the sum of the cart lines (not Shipping or Total).
    assert result.cart.sub_total == sum(entry.line_total for entry in result.cart.entries), result.cart
